-- InternPath – Supabase schema. Run the whole file in Supabase > SQL Editor.
-- ========== TABLES ==========
create table domains(slug text primary key,name text not null,icon text,sort_order int default 0);
create table companies(id bigint generated by default as identity primary key,name text not null,site text,location text,verified boolean not null default false);
create table sources(id bigint generated by default as identity primary key,name text not null,type text,trusted boolean not null default false);
create table internships(
 id bigint generated by default as identity primary key,
 title text not null,company_id bigint references companies(id) on delete set null,
 domain text references domains(slug) on delete set null,
 type text not null check(type in('paid','unpaid')),stipend text,
 mode text not null check(mode in('remote','onsite','hybrid')),
 months int not null check(months>0),years int[] not null default '{1,2,3,4}',
 departments text[] not null default '{ANY}',degrees text[] not null default '{ANY}',skills text[] not null default '{}',
 deadline date not null,source_id bigint references sources(id) on delete set null,
 apply_mode text not null default 'external' check(apply_mode in('internal','external')),apply_url text,
 admin_verified boolean not null default false,expired boolean not null default false,link_ok boolean,link_checked_at timestamptz,
 description text,created_at timestamptz not null default now());
create index on internships(domain);create index on internships(deadline);
create table profiles(user_id uuid primary key references auth.users(id) on delete cascade,name text,
 academic_year int check(academic_year between 1 and 6),degree text,department text,skills text[] default '{}',
 availability_months int,preferred_mode text check(preferred_mode in('remote','onsite','hybrid')),updated_at timestamptz default now());
create table admins(user_id uuid primary key references auth.users(id) on delete cascade);
create table saved_internships(user_id uuid references auth.users(id) on delete cascade,internship_id bigint references internships(id) on delete cascade,primary key(user_id,internship_id));
create table applications(id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,internship_id bigint not null references internships(id) on delete cascade,
 student_name text,student_email text,
 status text not null default 'Submitted' check(status in('Submitted','Applied (external)','In review','Interview','Offer','Rejected')),
 phone text,why text,resume text,created_at timestamptz not null default now(),unique(user_id,internship_id));
create table roadmap_progress(user_id uuid references auth.users(id) on delete cascade,slug text,step int,primary key(user_id,slug,step));

-- ========== HELPERS ==========
create or replace function is_admin() returns boolean language sql security definer stable set search_path=public as
$$ select exists(select 1 from admins where user_id=auth.uid()) $$;
create or replace function handle_new_user() returns trigger language plpgsql security definer set search_path=public as
$$ begin insert into profiles(user_id,name) values(new.id,coalesce(new.raw_user_meta_data->>'name',split_part(new.email,'@',1))) on conflict do nothing; return new; end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function handle_new_user();

-- ========== ROW LEVEL SECURITY ==========
alter table domains enable row level security;alter table companies enable row level security;alter table sources enable row level security;
alter table internships enable row level security;alter table profiles enable row level security;alter table admins enable row level security;
alter table saved_internships enable row level security;alter table applications enable row level security;alter table roadmap_progress enable row level security;
-- public catalogue: anyone reads, only admins write
create policy "read" on domains for select using(true);create policy "admin" on domains for all using(is_admin()) with check(is_admin());
create policy "read verified companies" on companies for select using(is_admin() or (
 verified and site is not null and site ~* '^https://'
 and site !~* '^https://(localhost|127\.|10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.|169\.254\.|0\.|\[)'
 and site !~* '\.(local|internal)(/|$)'
 and site !~* '(^|//)(localhost|[^/]*\.(example|invalid|test|localhost))(:[0-9]+)?(/|$)'
 and site !~* '(^|//)([^/]+\.)?example\.(com|net|org)(:[0-9]+)?(/|$)'
));create policy "admin" on companies for all using(is_admin()) with check(is_admin());
create policy "read" on sources for select using(true);create policy "admin" on sources for all using(is_admin()) with check(is_admin());
create policy "read verified opportunities" on internships for select using(is_admin() or (
 admin_verified and link_ok is true and not expired and deadline>=current_date
 and exists(select 1 from companies c where c.id=internships.company_id and c.verified
  and c.site is not null and c.site ~* '^https://'
  and c.site !~* '^https://(localhost|127\.|10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.|169\.254\.|0\.|\[)'
  and c.site !~* '\.(local|internal)(/|$)'
  and c.site !~* '(^|//)(localhost|[^/]*\.(example|invalid|test|localhost))(:[0-9]+)?(/|$)'
  and c.site !~* '(^|//)([^/]+\.)?example\.(com|net|org)(:[0-9]+)?(/|$)')
 and exists(select 1 from sources s where s.id=internships.source_id and s.trusted)
));create policy "admin" on internships for all using(is_admin()) with check(is_admin());
-- profiles
create policy "own read" on profiles for select using(user_id=auth.uid() or is_admin());
create policy "own insert" on profiles for insert with check(user_id=auth.uid());
create policy "own update" on profiles for update using(user_id=auth.uid()) with check(user_id=auth.uid());
-- admins: a user may only see their own row; nobody can write from the client
create policy "self" on admins for select using(user_id=auth.uid());
-- saved + progress: own rows only
create policy "own" on saved_internships for all using(user_id=auth.uid()) with check(user_id=auth.uid());
create policy "own" on roadmap_progress for all using(user_id=auth.uid()) with check(user_id=auth.uid());
-- applications: students see/create/update own; admins see and update all
create policy "read" on applications for select using(user_id=auth.uid() or is_admin());
create policy "insert" on applications for insert with check(user_id=auth.uid() and status in('Submitted','Applied (external)'));
create policy "update" on applications for update using(user_id=auth.uid() or is_admin()) with check(user_id=auth.uid() or is_admin());

